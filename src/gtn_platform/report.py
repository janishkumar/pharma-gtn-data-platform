"""Write every number the README quotes to reports/summary.{md,json}, from the warehouse."""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

SCENARIO_COLUMNS = {"bp_discount": "Best Price gap", "amp_nadac_factor": "AMP / NADAC"}


def money(value: float | None) -> str:
    if value is None:
        return "n/a"
    if abs(value) >= 1e9:
        return f"${value / 1e9:,.2f}B"
    if abs(value) >= 1e6:
        return f"${value / 1e6:,.1f}M"
    return f"${value:,.0f}"


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def rows(con: duckdb.DuckDBPyConnection, sql: str) -> list[dict]:
    cur = con.execute(sql)
    names = [d[0] for d in cur.description]
    return [dict(zip(names, r, strict=True)) for r in cur.fetchall()]


def collect(con: duckdb.DuckDBPyConnection) -> dict:
    latest_full = con.execute(
        "select max(year) from rpt_sensitivity where quarters = 4"
    ).fetchone()[0]
    return {
        "latest_full_year": latest_full,
        "coverage": rows(con, """
            select min(quarter_start) as first_quarter, max(quarter_start) as last_quarter,
                   count(*) as lines, count(distinct ndc) as ndcs,
                   sum(units) filter (where not is_suppressed) as units,
                   sum(medicaid_reimbursed) as medicaid_reimbursed,
                   avg(is_suppressed::int) as suppressed_line_share
            from fct_rebate_liability
        """)[0],
        "by_year": rows(con, """
            select year, quarters, liability_point, liability_high, priced_unit_share
            from rpt_sensitivity where is_base order by year
        """),
        "amp_source_units": rows(con, f"""
            select amp_source, sum(units) filter (where not is_suppressed) as units,
                   sum(liability_point) as liability_point
            from fct_rebate_liability where year = {latest_full}
            group by 1 order by 2 desc
        """),
        "category": rows(con, f"""
            select rebate_category, sum(medicaid_reimbursed) as medicaid_reimbursed,
                   sum(liability_point) as liability_point,
                   sum(liability_point) / sum(medicaid_reimbursed) as rebate_to_reimbursed
            from fct_rebate_liability where year = {latest_full}
            group by 1 order by 3 desc nulls last
        """),
        "capped_share_2023": con.execute("""
            select sum(units) filter (where is_capped) / sum(units)
            from fct_rebate_liability
            where year = 2023 and not is_suppressed and ura_per_unit is not null
        """).fetchone()[0],
        "sensitivity": rows(con, f"""
            select scenario, amp_nadac_factor, bp_discount, pre_nadac_excess_growth,
                   liability_point, liability_high
            from rpt_sensitivity where year = {latest_full}
            order by pre_nadac_excess_growth, amp_nadac_factor, bp_discount
        """),
        "validation": rows(con, "select * from rpt_validation_cms64 order by year"),
        "disputes": rows(con, f"""
            select reason_code, count(*) as lines, sum(dollars_at_stake) as dollars_at_stake
            from fct_dispute_candidates where year = {latest_full}
            group by 1 order by 3 desc nulls last
        """),
        "dispute_lines_distinct": con.execute(f"""
            select count(*), sum(dollars_at_stake) from (
                select distinct state, ndc, quarter_start, utilization_type, dollars_at_stake
                from fct_dispute_candidates where year = {latest_full})
        """).fetchone(),
    }


def render(s: dict) -> str:
    y = s["latest_full_year"]
    c = s["coverage"]
    base = next(r for r in s["by_year"] if r["year"] == y)
    out = [
        "# Summary (generated by `gtn report`)",
        "",
        f"Coverage: {c['first_quarter']} to {c['last_quarter']}, {c['lines']:,} utilization "
        f"lines, {c['ndcs']:,} NDCs, {money(c['medicaid_reimbursed'])} Medicaid reimbursed. "
        f"{pct(c['suppressed_line_share'])} of lines are suppressed by CMS.",
        "",
        f"## Base-case liability, {y}",
        "",
        f"Point {money(base['liability_point'])}, high {money(base['liability_high'])}. "
        f"Priced unit share {pct(base['priced_unit_share'])}.",
        "",
        "| Year | Quarters | Point | High | Priced units |",
        "|---|---|---|---|---|",
        *[
            f"| {r['year']} | {r['quarters']} | {money(r['liability_point'])} | "
            f"{money(r['liability_high'])} | {pct(r['priced_unit_share'])} |"
            for r in s["by_year"]
        ],
        "",
        f"## Sensitivity, {y} (point estimate)",
        "",
    ]
    grid: dict[tuple, dict] = {}
    for r in s["sensitivity"]:
        grid.setdefault((r["pre_nadac_excess_growth"], r["amp_nadac_factor"]), {})[
            r["bp_discount"]
        ] = r["liability_point"]
    bps = sorted({r["bp_discount"] for r in s["sensitivity"]})
    out += [
        "| Pre-2014 excess price growth | AMP / NADAC | "
        + " | ".join(f"Best Price gap {b:.0%}" for b in bps) + " |",
        "|---|---|" + "---|" * len(bps),
    ]
    for (g, f), by_bp in sorted(grid.items()):
        out.append(f"| {g:.0%} | {f:.2f} | " + " | ".join(money(by_bp[b]) for b in bps) + " |")
    out += ["", f"## AMP source, {y}", "", "| Source | Units | Liability |", "|---|---|---|"]
    out += [
        f"| {r['amp_source']} | {r['units']:,.0f} | {money(r['liability_point'])} |"
        for r in s["amp_source_units"]
    ]
    out += ["", f"## By drug category, {y}", "",
            "| Category | Medicaid reimbursed | Liability | Rebate / reimbursed |",
            "|---|---|---|---|"]
    out += [
        f"| {r['rebate_category']} | {money(r['medicaid_reimbursed'])} | "
        f"{money(r['liability_point'])} | {pct(r['rebate_to_reimbursed'])} |"
        for r in s["category"]
    ]
    out += ["", f"Share of priced 2023 units whose URA hit the 100% AMP cap: "
            f"{pct(s['capped_share_2023'])}", "", "## Validation against CMS-64", "",
            "| Year | CMS-64 national rebate offset | Estimate (point) | Estimate (high) | "
            "Point / reported |", "|---|---|---|---|---|"]
    out += [
        f"| {r['year']} | {money(r['cms64_national_rebate_offset'])} | "
        f"{money(r['estimate_point'])} | {money(r['estimate_high'])} | "
        f"{pct(r['point_to_reported'])} |"
        for r in s["validation"]
    ]
    n_lines, dollars = s["dispute_lines_distinct"]
    out += ["", f"## Dispute candidates, {y}", "",
            f"{n_lines:,} distinct lines, {money(dollars)} at stake.", "",
            "| Reason | Lines | Dollars at stake |", "|---|---|---|"]
    out += [
        f"| {r['reason_code']} | {r['lines']:,} | {money(r['dollars_at_stake'])} |"
        for r in s["disputes"]
    ]
    return "\n".join(out) + "\n"


def write_report(warehouse: Path, out_dir: Path) -> Path:
    con = duckdb.connect(str(warehouse), read_only=True)
    summary = collect(con)
    con.close()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2, default=str) + "\n")
    path = out_dir / "summary.md"
    path.write_text(render(summary))
    print(path.read_text())
    return path
